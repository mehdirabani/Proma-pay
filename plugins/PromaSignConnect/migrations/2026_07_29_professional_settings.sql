CREATE TABLE IF NOT EXISTS proma_connect_provider_configs (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  uuid CHAR(36) NOT NULL,
  provider_key VARCHAR(40) NOT NULL,
  title VARCHAR(120) NOT NULL,
  environment VARCHAR(20) NOT NULL DEFAULT 'production',
  external_bot_id VARCHAR(80) NULL,
  external_username VARCHAR(120) NULL,
  encrypted_secret LONGTEXT NULL,
  api_base_url VARCHAR(255) NULL,
  status VARCHAR(30) NOT NULL DEFAULT 'draft',
  is_active TINYINT(1) NOT NULL DEFAULT 0,
  is_default TINYINT(1) NOT NULL DEFAULT 0,
  capabilities_json LONGTEXT NOT NULL,
  retry_policy_json LONGTEXT NULL,
  health_json LONGTEXT NULL,
  last_tested_at DATETIME NULL,
  last_success_at DATETIME NULL,
  last_failure_at DATETIME NULL,
  created_by BIGINT UNSIGNED NULL,
  created_at DATETIME NOT NULL,
  updated_by BIGINT UNSIGNED NULL,
  updated_at DATETIME NULL,
  archived_at DATETIME NULL,
  UNIQUE KEY uq_provider_uuid (uuid),
  UNIQUE KEY uq_provider_title (provider_key,title,environment),
  KEY idx_provider_state (provider_key,is_active,status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
