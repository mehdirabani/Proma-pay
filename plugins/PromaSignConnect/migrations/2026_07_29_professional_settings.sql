CREATE TABLE IF NOT EXISTS proma_sign_hash_registry (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  public_id CHAR(36) NOT NULL,
  request_id BIGINT UNSIGNED NOT NULL,
  signer_id BIGINT UNSIGNED NULL,
  hash_type VARCHAR(40) NOT NULL,
  algorithm VARCHAR(30) NOT NULL DEFAULT 'sha256',
  algorithm_version VARCHAR(20) NOT NULL DEFAULT '1',
  canonicalization_version VARCHAR(30) NOT NULL DEFAULT 'json-c14n-v1',
  digest CHAR(64) NOT NULL,
  authenticity_hmac CHAR(64) NOT NULL,
  previous_event_hash CHAR(64) NULL,
  metadata_json LONGTEXT NULL,
  created_at DATETIME NOT NULL,
  UNIQUE KEY uq_hash_public (public_id),
  UNIQUE KEY uq_hash_type (request_id,signer_id,hash_type),
  KEY idx_hash_chain (request_id,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
