    public static function safeCode(array $body)
    {
        if (isset($body['data']['code'])) {
            return (int) $body['data']['code'];
        }
        if (isset($body['errors']['code'])) {
            return (int) $body['errors']['code'];
        }
        if (isset($body['errors'][0]['code'])) {
            return (int) $body['errors'][0]['code'];
        }
        return 0;
    }
