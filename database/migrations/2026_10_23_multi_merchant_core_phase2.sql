-- Additive Phase 2 merchant, site, connection, credential, policy, and audit schema.
-- Existing contract, installment, payment, and ledger rows are not modified.
CREATE TABLE IF NOT EXISTS merchant_accounts (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  merchant_uuid CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  merchant_code VARCHAR(80) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  display_name VARCHAR(190) NOT NULL,
  legal_name VARCHAR(190) DEFAULT NULL,
  contact_email VARCHAR(190) DEFAULT NULL,
  contact_mobile VARCHAR(32) DEFAULT NULL,
  status ENUM('pending','active','suspended','disabled') NOT NULL DEFAULT 'pending',
  created_by BIGINT UNSIGNED DEFAULT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_merchant_account_uuid (merchant_uuid),
  UNIQUE KEY uq_merchant_account_code (merchant_code),
  KEY idx_merchant_account_status (status,id),
  CONSTRAINT fk_merchant_account_creator FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS merchant_sites (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  merchant_id BIGINT UNSIGNED NOT NULL,
  site_uuid CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  site_code VARCHAR(80) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  display_name VARCHAR(190) NOT NULL,
  site_origin VARCHAR(270) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  verification_status ENUM('unverified','pending','verified','rejected') NOT NULL DEFAULT 'unverified',
  status ENUM('pending','active','suspended','disabled') NOT NULL DEFAULT 'pending',
  verified_at DATETIME DEFAULT NULL,
  created_by BIGINT UNSIGNED DEFAULT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_merchant_site_uuid (site_uuid),
  UNIQUE KEY uq_merchant_site_code (merchant_id,site_code),
  UNIQUE KEY uq_merchant_site_origin (merchant_id,site_origin),
  UNIQUE KEY uq_merchant_site_id_owner (id,merchant_id),
  KEY idx_merchant_site_status (merchant_id,status,verification_status),
  CONSTRAINT fk_merchant_site_merchant FOREIGN KEY (merchant_id) REFERENCES merchant_accounts (id) ON DELETE RESTRICT,
  CONSTRAINT fk_merchant_site_creator FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS merchant_connections (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  merchant_id BIGINT UNSIGNED NOT NULL,
  site_id BIGINT UNSIGNED NOT NULL,
  connection_uuid CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  connection_code VARCHAR(80) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  display_name VARCHAR(190) NOT NULL,
  api_version VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'v1',
  status ENUM('inactive','active','suspended','revoked') NOT NULL DEFAULT 'inactive',
  emergency_disabled TINYINT(1) NOT NULL DEFAULT 0,
  emergency_disabled_at DATETIME DEFAULT NULL,
  emergency_disabled_by BIGINT UNSIGNED DEFAULT NULL,
  emergency_disable_reason VARCHAR(500) DEFAULT NULL,
  rate_limit_per_minute SMALLINT UNSIGNED NOT NULL DEFAULT 60,
  created_by BIGINT UNSIGNED DEFAULT NULL,
  activated_by BIGINT UNSIGNED DEFAULT NULL,
  activated_at DATETIME DEFAULT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_merchant_connection_uuid (connection_uuid),
  UNIQUE KEY uq_merchant_connection_code (connection_code),
  UNIQUE KEY uq_merchant_connection_owner (id,merchant_id),
  UNIQUE KEY uq_merchant_connection_full_scope (id,merchant_id,site_id),
  KEY idx_merchant_connection_site_owner (site_id,merchant_id),
  KEY idx_merchant_connection_status (merchant_id,site_id,status,emergency_disabled),
  CONSTRAINT fk_merchant_connection_site_owner FOREIGN KEY (site_id,merchant_id) REFERENCES merchant_sites (id,merchant_id) ON DELETE RESTRICT,
  CONSTRAINT fk_merchant_connection_creator FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE SET NULL,
  CONSTRAINT fk_merchant_connection_activator FOREIGN KEY (activated_by) REFERENCES users (id) ON DELETE SET NULL,
  CONSTRAINT fk_merchant_connection_emergency_user FOREIGN KEY (emergency_disabled_by) REFERENCES users (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS merchant_memberships (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  merchant_id BIGINT UNSIGNED NOT NULL,
  user_id BIGINT UNSIGNED NOT NULL,
  membership_role ENUM('owner','admin','operator','finance','viewer') NOT NULL,
  status ENUM('invited','active','suspended') NOT NULL DEFAULT 'invited',
  granted_by BIGINT UNSIGNED DEFAULT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_merchant_membership_user (merchant_id,user_id),
  KEY idx_merchant_membership_user_status (user_id,status,merchant_id),
  CONSTRAINT fk_merchant_membership_merchant FOREIGN KEY (merchant_id) REFERENCES merchant_accounts (id) ON DELETE RESTRICT,
  CONSTRAINT fk_merchant_membership_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE RESTRICT,
  CONSTRAINT fk_merchant_membership_grantor FOREIGN KEY (granted_by) REFERENCES users (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS merchant_api_credentials (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  connection_id BIGINT UNSIGNED NOT NULL,
  credential_uuid CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  token_prefix VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  token_hash BINARY(32) NOT NULL,
  environment ENUM('test','live') NOT NULL DEFAULT 'test',
  scopes_json LONGTEXT NOT NULL,
  status ENUM('active','revoked') NOT NULL DEFAULT 'active',
  issued_by BIGINT UNSIGNED DEFAULT NULL,
  issued_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  expires_at DATETIME DEFAULT NULL,
  revoked_by BIGINT UNSIGNED DEFAULT NULL,
  revoked_at DATETIME DEFAULT NULL,
  last_used_at DATETIME DEFAULT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uq_merchant_credential_uuid (credential_uuid),
  UNIQUE KEY uq_merchant_credential_hash (token_hash),
  KEY idx_merchant_credential_connection (connection_id,status,expires_at),
  CONSTRAINT fk_merchant_credential_connection FOREIGN KEY (connection_id) REFERENCES merchant_connections (id) ON DELETE RESTRICT,
  CONSTRAINT fk_merchant_credential_issuer FOREIGN KEY (issued_by) REFERENCES users (id) ON DELETE SET NULL,
  CONSTRAINT fk_merchant_credential_revoker FOREIGN KEY (revoked_by) REFERENCES users (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS merchant_policy_versions (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  connection_id BIGINT UNSIGNED NOT NULL,
  policy_version_uuid CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  policy_type ENUM('financial','guarantee','commission','settlement') NOT NULL,
  version_no INT UNSIGNED NOT NULL,
  policy_json LONGTEXT NOT NULL,
  content_sha256 CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  status ENUM('draft','published','retired') NOT NULL DEFAULT 'draft',
  created_by BIGINT UNSIGNED DEFAULT NULL,
  published_by BIGINT UNSIGNED DEFAULT NULL,
  published_at DATETIME DEFAULT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_merchant_policy_uuid (policy_version_uuid),
  UNIQUE KEY uq_merchant_policy_version (connection_id,policy_type,version_no),
  UNIQUE KEY uq_merchant_policy_head_fk (id,connection_id,policy_type),
  KEY idx_merchant_policy_status (connection_id,policy_type,status,version_no),
  CONSTRAINT fk_merchant_policy_connection FOREIGN KEY (connection_id) REFERENCES merchant_connections (id) ON DELETE RESTRICT,
  CONSTRAINT fk_merchant_policy_creator FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE SET NULL,
  CONSTRAINT fk_merchant_policy_publisher FOREIGN KEY (published_by) REFERENCES users (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS merchant_policy_heads (
  connection_id BIGINT UNSIGNED NOT NULL,
  policy_type ENUM('financial','guarantee','commission','settlement') NOT NULL,
  policy_version_id BIGINT UNSIGNED NOT NULL,
  selected_by BIGINT UNSIGNED DEFAULT NULL,
  selected_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (connection_id,policy_type),
  KEY idx_merchant_policy_head_version (policy_version_id),
  CONSTRAINT fk_merchant_policy_head_connection FOREIGN KEY (connection_id) REFERENCES merchant_connections (id) ON DELETE RESTRICT,
  CONSTRAINT fk_merchant_policy_head_version FOREIGN KEY (policy_version_id,connection_id,policy_type) REFERENCES merchant_policy_versions (id,connection_id,policy_type) ON DELETE RESTRICT,
  CONSTRAINT fk_merchant_policy_head_selector FOREIGN KEY (selected_by) REFERENCES users (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS merchant_audit_events (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  event_uuid CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  merchant_id BIGINT UNSIGNED NOT NULL,
  site_id BIGINT UNSIGNED DEFAULT NULL,
  connection_id BIGINT UNSIGNED DEFAULT NULL,
  actor_user_id BIGINT UNSIGNED DEFAULT NULL,
  event_type VARCHAR(80) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  subject_type VARCHAR(60) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  subject_uuid CHAR(36) CHARACTER SET ascii COLLATE ascii_bin DEFAULT NULL,
  request_id VARCHAR(100) CHARACTER SET ascii COLLATE ascii_bin DEFAULT NULL,
  metadata_json LONGTEXT NOT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_merchant_audit_event_uuid (event_uuid),
  KEY idx_merchant_audit_timeline (merchant_id,created_at,id),
  KEY idx_merchant_audit_connection (connection_id,created_at,id),
  KEY idx_merchant_audit_subject (merchant_id,subject_type,subject_uuid),
  CONSTRAINT fk_merchant_audit_merchant FOREIGN KEY (merchant_id) REFERENCES merchant_accounts (id) ON DELETE RESTRICT,
  CONSTRAINT fk_merchant_audit_site FOREIGN KEY (site_id) REFERENCES merchant_sites (id) ON DELETE SET NULL,
  CONSTRAINT fk_merchant_audit_connection FOREIGN KEY (connection_id) REFERENCES merchant_connections (id) ON DELETE SET NULL,
  CONSTRAINT fk_merchant_audit_actor FOREIGN KEY (actor_user_id) REFERENCES users (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;